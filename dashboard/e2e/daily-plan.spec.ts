test('daily plan fits the console and supports the whole daily workflow', async ({ page }) => {
  await signInWithSimulator(page)
  await page.locator('details.mission-nav summary').click()
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Daily plan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Daily plan', exact: true })).toBeVisible()
  await expect(page.getByText('Simulated day', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Very tired', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Accept change', exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/ouranos-daily-plan-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Accept change', exact: true }).click()
  await expect(page.getByText('Changes accepted. Your plan is up to date.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Accept change', exact: true })).toHaveCount(0)
  await page.locator('.plan-deferred summary').click()
  await page.getByRole('button', { name: 'Restore today' }).click()
  await page.getByRole('button', { name: 'Rested', exact: true }).click()
  await page.getByRole('button', { name: 'Somewhat tired', exact: true }).click()
  await page.getByRole('button', { name: 'Keep current times' }).click()
  await expect(page.getByRole('button', { name: 'Accept change', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Add activity', exact: true }).click()
  await page.getByLabel('Activity', { exact: true }).fill('Equipment check')
  await page.getByLabel('Start · UTC').fill('18:00')
  await page.getByRole('button', { name: 'Save activity' }).click()
  await page.getByRole('button', { name: /Equipment check Flexible/ }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Activity', { exact: true }).fill('Updated equipment check')
  await page.getByRole('button', { name: 'Save activity' }).click()
  await page.getByRole('button', { name: 'Mark complete', exact: true }).click()
  await expect(page.getByRole('button', { name: /Updated equipment check Complete/ })).toBeVisible()
  await page.getByRole('button', { name: 'Research session Fixed · 90 min' }).click()
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Running 15 min late', exact: true }).click()
  await expect(page.getByText('Research session overlaps Prescribed exercise. Crew review needed.')).toBeVisible()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('button', { name: 'Remove activity', exact: true }).click()
  await page.getByRole('button', { name: 'Add activity', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.locator('.plan-sleep summary').click()
  await page.getByLabel('Start of your planned sleep').fill('21:00')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Sleep boundary updated.')).toBeVisible()
  await page.locator('.plan-explainer summary').click()
  await expect(page.getByRole('link', { name: /NASA · Medical operations/ })).toHaveAttribute('href', 'https://www.nasa.gov/reference/6-0-medical-operations/')
})

test('a paired watch can update the console plan without stale writes', async ({ page }) => {
  const { watchToken } = await signInWithWatch(page)
  const [{ deviceId }] = await (await page.request.get('/api/watch-links')).json()
  await page.request.post(`/api/planner/${deviceId}`, { data: { plan: { ...demoDay(), simulated: false }, expectedRevision: 0 } })
  await page.goto('/#/plan')
  await expect(page.getByText('Shared with your paired watch', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Inventory review Flexible/ })).toBeVisible()
  const response = await page.request.post('/api/planner-action', { headers: { Authorization: `Bearer ${watchToken}` }, data: { expectedRevision: 1, action: { type: 'checkin', fatigue: 'very' } } })
  expect(response.status()).toBe(200)
  await expect(page.getByRole('button', { name: 'Very tired', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Accept change', exact: true }).click()
  await expect(page.getByText('Changes accepted. Your plan is up to date.')).toBeVisible()
  const watch = await (await page.request.get('/api/planner', { headers: { Authorization: `Bearer ${watchToken}` } })).json()
  expect(watch.tasks.find((t: { id: string }) => t.id === 'inventory').deferred).toBe(true)
  expect(watch.revision).toBe(3)
})
